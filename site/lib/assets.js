// Asset pipeline: self-hosted webfonts, KaTeX stylesheet, site CSS/JS.
// Nothing is fetched from a CDN at runtime -- the whole site is self-contained.

import fs from 'node:fs/promises'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)

const ROOT = path.resolve(import.meta.dirname, '..')
const SRC = path.join(ROOT, 'src')

// Which fontsource stylesheets to pull @font-face rules from. `index.css` is
// the weight-axis variable font; the italic file is a separate stylesheet.
const FONT_SOURCES = [
  { pkg: '@fontsource-variable/source-serif-4', files: ['index.css', 'wght-italic.css'] },
  { pkg: '@fontsource-variable/jetbrains-mono', files: ['index.css', 'wght-italic.css'] },
]

// Only latin subsets ship. Add more here if you start writing in other scripts.
const SUBSET_RE = /-latin(-ext)?-/

/**
 * Extracts the latin @font-face rules, copies the referenced .woff2 files into
 * dist/assets/fonts/, and returns the rewritten CSS.
 */
async function buildFontCss(outDir) {
  const fontsDir = path.join(outDir, 'assets', 'fonts')
  await fs.mkdir(fontsDir, { recursive: true })

  const rules = []

  for (const { pkg, files } of FONT_SOURCES) {
    const pkgDir = path.dirname(require.resolve(`${pkg}/package.json`))

    for (const file of files) {
      const css = await fs.readFile(path.join(pkgDir, file), 'utf8')

      for (const block of css.match(/@font-face\s*\{[^}]*\}/g) || []) {
        const match = block.match(/url\(\.\/files\/([^)]+)\)/)
        if (!match || !SUBSET_RE.test(match[1])) continue

        const filename = match[1]
        await fs.copyFile(
          path.join(pkgDir, 'files', filename),
          path.join(fontsDir, filename),
        )
        rules.push(block.replace(/url\(\.\/files\//g, 'url(fonts/'))
      }
    }
  }

  return `/* Self-hosted webfonts (generated by lib/assets.js -- do not edit) */\n${rules.join('\n')}\n`
}

/** KaTeX stylesheet + the woff2 half of its font set. */
async function copyKatex(outDir) {
  const katexDir = path.dirname(require.resolve('katex/package.json'))
  const distDir = path.join(katexDir, 'dist')
  const fontsOut = path.join(outDir, 'assets', 'fonts')

  await fs.mkdir(fontsOut, { recursive: true })
  await fs.copyFile(
    path.join(distDir, 'katex.min.css'),
    path.join(outDir, 'assets', 'katex.min.css'),
  )

  // woff2 is enough for every browser we care about; skipping woff/ttf saves
  // roughly two thirds of the payload.
  const fonts = await fs.readdir(path.join(distDir, 'fonts'))
  for (const f of fonts.filter((f) => f.endsWith('.woff2'))) {
    await fs.copyFile(path.join(distDir, 'fonts', f), path.join(fontsOut, f))
  }
}

/** Recursively copy a directory if it exists. */
export async function copyDir(from, to) {
  try {
    await fs.access(from)
  } catch {
    return
  }
  await fs.cp(from, to, { recursive: true })
}

export async function buildAssets(outDir, { dev = false } = {}) {
  const assetsDir = path.join(outDir, 'assets')
  await fs.mkdir(assetsDir, { recursive: true })

  const [fontCss, mainCss, siteJs] = await Promise.all([
    buildFontCss(outDir),
    fs.readFile(path.join(SRC, 'styles', 'main.css'), 'utf8'),
    fs.readFile(path.join(SRC, 'scripts', 'site.js'), 'utf8'),
    copyKatex(outDir),
  ])

  // One stylesheet, one request.
  await fs.writeFile(path.join(assetsDir, 'main.css'), `${fontCss}\n${mainCss}`)
  await fs.writeFile(path.join(assetsDir, 'site.js'), siteJs)

  if (dev) {
    await fs.writeFile(
      path.join(assetsDir, 'livereload.js'),
      `new EventSource('/__reload').onmessage = () => location.reload()\n`,
    )
  }

  // Anything in src/public is copied verbatim to the site root.
  await copyDir(path.join(SRC, 'public'), outDir)
}
